package io.smithy.beam.erlang;

import io.smithy.beam.core.BeamS3CustomizationIndex;
import software.amazon.smithy.model.shapes.ServiceShape;

/**
 * Emits {@code s3_endpoint.erl} bucket virtual-host and path-style helpers for S3 REST-XML clients.
 */
public final class ErlangS3EndpointEmitter {

    private ErlangS3EndpointEmitter() {}

    public static void emit(ErlangContext ctx, ServiceShape service) {
        if (!BeamS3CustomizationIndex.isS3Service(service)) {
            return;
        }

        ctx.writerDelegator().useFileWriter("s3_endpoint.erl", writer -> {
            writer.write("%% S3 bucket addressing helpers for $L (generated).", service.getId());
            writer.write("%% DO NOT EDIT -- generated by smithy-beam codegen.");
            writer.write("-module(s3_endpoint).");
            writer.write("-export([resolve_bucket_url/3, region_host/1]).");
            writer.write("");
            writer.write("-type client_config() :: #{binary() => term()}.");
            writer.write("");
            writer.write("-spec region_host(client_config()) -> binary().");
            writer.write("region_host(Config) ->");
            writer.indent();
            writer.write("BaseUrl = maps:get(base_url, Config, <<>>),");
            writer.write("{_Scheme, Authority} = split_base_url(BaseUrl),");
            writer.write("Authority.");
            writer.dedent();
            writer.write("");
            writer.write("-spec resolve_bucket_url(client_config(), binary(), binary()) ->");
            writer.write("    {binary(), binary()}.");
            writer.write("resolve_bucket_url(Config, Bucket, Key) ->");
            writer.indent();
            writer.write("Style = maps:get(s3_addressing_style, Config, virtual_host),");
            writer.write("RegionHost = region_host(Config),");
            writer.write("KeyPath = key_path(Key),");
            writer.write("case Style of");
            writer.indent();
            writer.write("virtual_host ->");
            writer.indent();
            writer.write("Host = virtual_host(Config, Bucket, RegionHost),");
            writer.write("{Host, KeyPath};");
            writer.dedent();
            writer.write("path_style ->");
            writer.indent();
            writer.write("{RegionHost, <<\"/\", Bucket/binary, KeyPath/binary>>};");
            writer.dedent();
            writer.write("_ ->");
            writer.indent();
            writer.write("Host = virtual_host(Config, Bucket, RegionHost),");
            writer.write("{Host, KeyPath}");
            writer.dedent();
            writer.dedent();
            writer.write("end.");
            writer.dedent();
            writer.write("");
            writer.write("key_path(<<>>) -> <<>>;");
            writer.write("key_path(Key) -> <<\"/\", Key/binary>>.");
            writer.write("");
            writer.write("virtual_host(Config, Bucket, RegionHost) ->");
            writer.indent();
            writer.write("case maps:get(s3_use_accelerate, Config, false) of");
            writer.indent();
            writer.write("true -> <<Bucket/binary, \".s3-accelerate.amazonaws.com\">>;");
            writer.write("false ->");
            writer.indent();
            writer.write("Suffix = s3_host_suffix(Config),");
            writer.write("<<Bucket/binary, Suffix/binary, RegionHost/binary>>");
            writer.dedent();
            writer.dedent();
            writer.write("end.");
            writer.dedent();
            writer.write("");
            writer.write("s3_host_suffix(Config) ->");
            writer.indent();
            writer.write("case maps:get(s3_use_dualstack, Config, false) of");
            writer.indent();
            writer.write("true -> <<\".s3.dualstack.\">>;");
            writer.write("false -> <<\".s3.\">>");
            writer.dedent();
            writer.write("end.");
            writer.dedent();
            writer.write("");
            writer.write("split_base_url(<<>>) ->");
            writer.indent();
            writer.write("{<<>>, <<>>};");
            writer.dedent();
            writer.write("split_base_url(BaseUrl) ->");
            writer.indent();
            writer.write("case uri_string:parse(BaseUrl) of");
            writer.indent();
            writer.write("#{scheme := Scheme, host := Host} = Parts ->");
            writer.indent();
            writer.write("PortSuffix = case maps:get(port, Parts, undefined) of");
            writer.indent();
            writer.write("undefined -> <<>>;");
            writer.write("Port -> <<\":\", (integer_to_binary(Port))/binary>>");
            writer.dedent();
            writer.write("end,");
            writer.write("{<< (list_to_binary(Scheme))/binary, \"://\">>,");
            writer.write(" << (list_to_binary(Host))/binary, PortSuffix/binary >>};");
            writer.dedent();
            writer.write("_ ->");
            writer.indent();
            writer.write("{<<>>, BaseUrl}");
            writer.dedent();
            writer.dedent();
            writer.write("end.");
            writer.dedent();
        });
    }
}
