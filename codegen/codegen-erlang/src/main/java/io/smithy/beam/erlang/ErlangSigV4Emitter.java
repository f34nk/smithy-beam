package io.smithy.beam.erlang;

import io.smithy.beam.core.BeamErlangLayout;
import io.smithy.beam.core.BeamSigV4Metadata;
import software.amazon.smithy.model.shapes.ServiceShape;

/**
 * Emits a self-contained {@code <service>_sigv4.erl} signing module for services with
 * {@code @aws.auth#sigv4}. Callers may supply credentials in client config or
 * rely on the generated credential provider module.
 */
public final class ErlangSigV4Emitter {

    private ErlangSigV4Emitter() {}

    public static void emit(ErlangContext ctx, ServiceShape service) {
        if (BeamSigV4Metadata.from(service).isEmpty()) {
            return;
        }

        BeamErlangLayout layout = new BeamErlangLayout(
                ctx.settings(), service.getId().getNamespace(), service);
        String sigv4Module = layout.sigv4ModuleName();

        ctx.writerDelegator().useFileWriter(layout.sigv4ModuleFile(), writer -> {
            writer.write("%% Generated SigV4 signing hook for $L.", service.getId());
            writer.write("-module($L).", sigv4Module);
            writer.write("-include(\"$L\").", layout.runtimeTypesHeaderFile());
            writer.write("-export([sign/3, presign/5, endpoint_host_from_config/1]).");
            writer.write("");
            writer.write("-type client_config() :: #{binary() => term()}.");
            writer.write("-spec sign(client_config(), Operation :: atom(), http_request()) -> http_request().");
            writer.write("sign(Config, Operation, Request) ->");
            writer.indent();
            writer.write("Credentials = maps:get(credentials, Config),");
            writer.write("Region = maps:get(region, Config, <<\"us-east-1\">>),");
            writer.write("Service = maps:get(signing_name, Config),");
            writer.write("Unsigned = maps:get({unsigned_payload, Operation}, Config, false),");
            writer.write("Opts = #{");
            writer.write("    unsigned_payload => Unsigned,");
            writer.write("    endpoint_host => endpoint_host_from_config(Config)");
            writer.write("},");
            writer.write("sign_request(Request, Credentials, Region, Service, Opts).");
            writer.dedent();
            writer.write("");
            writer.write("-spec presign(http_request(), map(), binary(), binary(), map()) ->");
            writer.write("    {ok, binary()} | {error, term()}.");
            writer.write("presign(Request, Credentials, Region, Service, Opts) ->");
            writer.indent();
            writer.write("AccessKeyId = maps:get(access_key_id, Credentials),");
            writer.write("SecretAccessKey = maps:get(secret_access_key, Credentials),");
            writer.write("DateTime = calendar:universal_time(),");
            writer.write("Host = resolve_host(Request, Opts),");
            writer.write("Url = build_url(Host, Request#http_request.path, Request#http_request.query),");
            writer.write("Ttl = maps:get(expires, Opts, 900),");
            writer.write("QueryOpts =");
            writer.write("    [");
            writer.write("        {ttl, Ttl},");
            writer.write("        {uri_encode_path, Service =/= <<\"s3\">>}");
            writer.write("    ]");
            writer.write("    ++ body_digest_option(Opts)");
            writer.write("    ++ session_token_option(maps:get(session_token, Credentials, undefined)),");
            writer.write("try");
            writer.indent();
            writer.write("{ok, aws_signature:sign_v4_query_params(");
            writer.indent();
            writer.write("AccessKeyId,");
            writer.write("SecretAccessKey,");
            writer.write("Region,");
            writer.write("Service,");
            writer.write("DateTime,");
            writer.write("Request#http_request.method,");
            writer.write("Url,");
            writer.write("QueryOpts");
            writer.write(")}");
            writer.dedent();
            writer.dedent();
            writer.write("catch");
            writer.indent();
            writer.write("_:Reason ->");
            writer.indent();
            writer.write("{error, Reason}");
            writer.dedent();
            writer.dedent();
            writer.write("end.");
            writer.dedent();
            writer.write("");
            writer.write("-spec sign_request(http_request(), map(), binary(), binary(), map()) -> http_request().");
            writer.write("sign_request(Request, Credentials, Region, Service, Opts) ->");
            writer.indent();
            writer.write("AccessKeyId = maps:get(access_key_id, Credentials),");
            writer.write("SecretAccessKey = maps:get(secret_access_key, Credentials),");
            writer.write("DateTime = calendar:universal_time(),");
            writer.write("Host = resolve_host(Request, Opts),");
            writer.write("Url = build_url(Host, Request#http_request.path, Request#http_request.query),");
            writer.write("Headers0 = ensure_host_header(Request#http_request.headers, Host),");
            writer.write("Headers1 = maybe_add_session_token(Headers0, maps:get(session_token, Credentials, undefined)),");
            writer.write("SignOpts = sign_options(Service, Opts),");
            writer.write("SignedHeaders = aws_signature:sign_v4(");
            writer.indent();
            writer.write("AccessKeyId,");
            writer.write("SecretAccessKey,");
            writer.write("Region,");
            writer.write("Service,");
            writer.write("DateTime,");
            writer.write("Request#http_request.method,");
            writer.write("Url,");
            writer.write("Headers1,");
            writer.write("Request#http_request.body,");
            writer.write("SignOpts");
            writer.dedent();
            writer.write("),");
            writer.write("Request#http_request{headers = SignedHeaders}.");
            writer.dedent();
            writer.write("");
            writer.write("resolve_host(#http_request{host = Host, headers = Headers}, Opts) ->");
            writer.indent();
            writer.write("coalesce([");
            writer.write("    Host,");
            writer.write("    maps:get(host, Opts, undefined),");
            writer.write("    maps:get(endpoint_host, Opts, undefined),");
            writer.write("    header_host(Headers)");
            writer.write("]).");
            writer.dedent();
            writer.write("");
            writer.write("coalesce([H | Rest]) ->");
            writer.indent();
            writer.write("case H of");
            writer.indent();
            writer.write("undefined -> coalesce(Rest);");
            writer.write("<<>> -> coalesce(Rest);");
            writer.write("Value -> Value");
            writer.dedent();
            writer.write("end;");
            writer.dedent();
            writer.write("coalesce([]) ->");
            writer.indent();
            writer.write("<<\"localhost\">>.");
            writer.dedent();
            writer.write("");
            writer.write("build_url(Host, Path, Query) ->");
            writer.indent();
            writer.write("<<\"https://\", Host/binary, Path/binary, (query_suffix(Query))/binary>>.");
            writer.dedent();
            writer.write("");
            writer.write("query_suffix(Query) when map_size(Query) =:= 0 ->");
            writer.indent();
            writer.write("<<>>;");
            writer.dedent();
            writer.write("query_suffix(Query) ->");
            writer.indent();
            writer.write("Params = uri_string:compose_query([{K, V} || {K, V} <- maps:to_list(Query)]),");
            writer.write("<<\"?\", Params/binary>>.");
            writer.dedent();
            writer.write("");
            writer.write("ensure_host_header(Headers, Host) ->");
            writer.indent();
            writer.write("case header_host(Headers) of");
            writer.indent();
            writer.write("undefined -> [{<<\"host\">>, Host} | Headers];");
            writer.write("_ -> Headers");
            writer.dedent();
            writer.write("end.");
            writer.dedent();
            writer.write("");
            writer.write("header_host(Headers) ->");
            writer.indent();
            writer.write("proplists:get_value(<<\"host\">>, Headers, proplists:get_value(<<\"Host\">>, Headers)).");
            writer.dedent();
            writer.write("");
            writer.write("maybe_add_session_token(Headers, undefined) ->");
            writer.indent();
            writer.write("Headers;");
            writer.dedent();
            writer.write("maybe_add_session_token(Headers, Token) ->");
            writer.indent();
            writer.write("case proplists:get_value(<<\"x-amz-security-token\">>, Headers) of");
            writer.indent();
            writer.write("undefined -> [{<<\"x-amz-security-token\">>, Token} | Headers];");
            writer.write("_ -> Headers");
            writer.dedent();
            writer.write("end.");
            writer.dedent();
            writer.write("");
            writer.write("sign_options(Service, Opts) ->");
            writer.indent();
            writer.write("[{uri_encode_path, Service =/= <<\"s3\">>}] ++ body_digest_option(Opts).");
            writer.dedent();
            writer.write("");
            writer.write("body_digest_option(Opts) ->");
            writer.indent();
            writer.write("case maps:get(unsigned_payload, Opts, false) of");
            writer.indent();
            writer.write("true -> [{body_digest, <<\"UNSIGNED-PAYLOAD\">>}];");
            writer.write("false -> []");
            writer.dedent();
            writer.write("end.");
            writer.dedent();
            writer.write("");
            writer.write("session_token_option(undefined) ->");
            writer.indent();
            writer.write("[];");
            writer.dedent();
            writer.write("session_token_option(Token) ->");
            writer.indent();
            writer.write("[{session_token, Token}].");
            writer.dedent();
            writer.write("");
            writer.write("endpoint_host_from_config(Config) ->");
            writer.indent();
            writer.write("case maps:get(base_url, Config, undefined) of");
            writer.indent();
            writer.write("undefined ->");
            writer.indent();
            writer.write("case {maps:get(endpoint_prefix, Config, undefined),");
            writer.write("      maps:get(region, Config, <<\"us-east-1\">>)} of");
            writer.indent();
            writer.write("{undefined, _} -> undefined;");
            writer.write("{Prefix, Region} -> <<Prefix/binary, \".\", Region/binary, \".amazonaws.com\">>");
            writer.dedent();
            writer.write("end;");
            writer.dedent();
            writer.write("BaseUrl ->");
            writer.indent();
            writer.write("{_Scheme, Authority} = split_base_url(BaseUrl),");
            writer.write("Authority");
            writer.dedent();
            writer.dedent();
            writer.write("end.");
            writer.dedent();
            writer.write("");
            writer.write("split_base_url(<<>>) ->");
            writer.indent();
            writer.write("{<<>>, <<>>};");
            writer.dedent();
            writer.write("split_base_url(BaseUrl) ->");
            writer.indent();
            writer.write("case uri_string:parse(binary_to_list(BaseUrl)) of");
            writer.indent();
            writer.write("#{scheme := Scheme, host := Host} = Parts ->");
            writer.indent();
            writer.write("PortSuffix = case maps:get(port, Parts, undefined) of");
            writer.indent();
            writer.write("undefined -> <<>>;");
            writer.write("Port -> <<\":\", (integer_to_binary(Port))/binary>>");
            writer.dedent();
            writer.write("end,");
            writer.write("{<< (list_to_binary(Scheme))/binary, \"://\">>,");
            writer.write(" << (list_to_binary(Host))/binary, PortSuffix/binary >>};");
            writer.dedent();
            writer.write("_ ->");
            writer.indent();
            writer.write("{<<>>, BaseUrl}");
            writer.dedent();
            writer.dedent();
            writer.write("end.");
            writer.dedent();
        });
    }
}
