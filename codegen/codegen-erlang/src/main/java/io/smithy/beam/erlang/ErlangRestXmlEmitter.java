    private static void emitBuildHostHelpers(
            ErlangWriter writer, Model model, ServiceShape service, SymbolProvider sp) {
        writer.write("split_base_url(BaseUrl) ->");
        writer.indent();
        writer.write("case uri_string:parse(binary_to_list(BaseUrl)) of");
        writer.indent();
        writer.write("#{scheme := Scheme, host := Host} = Parts ->");
        writer.indent();
        writer.write("PortSuffix = case maps:get(port, Parts, undefined) of");
        writer.indent();
        writer.write("undefined -> <<>>;");
        writer.write("Port -> <<\":\", (integer_to_binary(Port))/binary>>");
        writer.dedent();
        writer.write("end,");
        writer.write("{<< (list_to_binary(Scheme))/binary, \"://\">>,");
        writer.write(" << (list_to_binary(Host))/binary, PortSuffix/binary >>};");
        writer.dedent();
        writer.write("_ ->");
        writer.indent();
        writer.write("{<<>>, BaseUrl}");
        writer.dedent();
        writer.dedent();
        writer.write("end.");
        writer.dedent();
        writer.write("");

        BeamHostLabelIndex hostLabelIndex = BeamHostLabelIndex.of(model);
        for (OperationShape op : ErlangTopDown.containedOperationsSorted(model, service)) {
            List<MemberShape> hostLabels = hostLabelIndex.hostLabelMembers(op);
            if (hostLabels.isEmpty() || !op.hasTrait(EndpointTrait.class)) {
                continue;
            }
            StructureShape input = model.expectShape(op.getInputShape(), StructureShape.class);
            String inputRecord = recordName(sp.toSymbol(input));
            SmithyPattern hostPrefix = op.expectTrait(EndpointTrait.class).getHostPrefix();
            String prefixExpr = buildHostPrefixExpression(hostPrefix);
            List<String> patternParts = hostLabels.stream()
                    .map(m -> {
                        String field = BeamNameUtils.toSnakeCase(m.getMemberName());
                        return field + " = " + toBindingVar(field);
                    })
                    .toList();
            String pattern = patternParts.isEmpty()
                    ? "" : "\n    " + String.join(",\n    ", patternParts) + "\n";

            writer.write("build_host(#$L{$L}, Config) ->", inputRecord, pattern);
            writer.indent();
            writer.write("BaseUrl = maps:get(base_url, Config, <<>>),");
            writer.write("{_Scheme, Authority} = split_base_url(BaseUrl),");
            writer.write("Prefix = $L,", prefixExpr);
            writer.write("<<Prefix/binary, Authority/binary>>.");
            writer.dedent();
            writer.write("");
        }
    }

    public static boolean serviceHasHostLabelOperations(Model model, ServiceShape service) {
        BeamHostLabelIndex hostLabelIndex = BeamHostLabelIndex.of(model);
        for (OperationShape op : ErlangTopDown.containedOperationsSorted(model, service)) {
            if (!hostLabelIndex.hostLabelMembers(op).isEmpty() && op.hasTrait(EndpointTrait.class)) {
                return true;
            }
        }
        return false;
    }

    public static boolean serviceEncodesWithConfig(Model model, ServiceShape service) {
        return serviceHasHostLabelOperations(model, service)
                || BeamS3CustomizationIndex.of(model).serviceUsesBucketAddressing(service);
    }

    private static String recordName(Symbol symbol) {
        return symbol.getName().replace("()", "");
    }

    private static List<String> buildPatternParts(
            List<HttpBinding> labels,
            List<HttpBinding> queries,
            List<HttpBinding> queryParams,
            List<HttpBinding> headers,
            List<HttpBinding> prefixHeaders,
            List<HttpBinding> payloadMembers) {
        List<String> parts = new ArrayList<>();
        for (HttpBinding b : concat(labels, queries, queryParams, headers, prefixHeaders, payloadMembers)) {
            String field = BeamNameUtils.toSnakeCase(b.getMember().getMemberName());
            parts.add(field + " = " + toBindingVar(field));
        }
        return parts;
    }

    private static String toBindingVar(String snakeField) {
        return BeamNameUtils.toCamelCaseVariable(snakeField);
    }

    @SafeVarargs
    private static <T> List<T> concat(List<T>... lists) {
        List<T> out = new ArrayList<>();
        for (List<T> l : lists) {
            out.addAll(l);
        }
        return out;
    }

    private static String buildPathExpression(String uriTemplate, List<HttpBinding> labels) {
        if (labels.isEmpty()) {
            return "<<\"" + uriTemplate + "\">>";
        }
        StringBuilder sb = new StringBuilder("<<");
        int pos = 0;
        while (pos < uriTemplate.length()) {
            int start = uriTemplate.indexOf('{', pos);
            if (start < 0) {
                sb.append("\"").append(uriTemplate.substring(pos)).append("\"");
                break;
            }
            if (start > pos) {
                sb.append("\"").append(uriTemplate, pos, start).append("\", ");
            }
            int end = uriTemplate.indexOf('}', start);
            String labelName = uriTemplate.substring(start + 1, end);
            String fieldName = BeamNameUtils.toSnakeCase(labelName);
            sb.append("(uri_encode(to_binary(").append(toBindingVar(fieldName)).append(")))/binary");
            pos = end + 1;
            if (pos < uriTemplate.length()) {
                sb.append(", ");
            }
        }
        sb.append(">>");
        return sb.toString();
    }

    private static String buildHostPrefixExpression(SmithyPattern hostPrefix) {
        if (hostPrefix.getSegments().isEmpty()) {
            return "<<>>";
        }
        StringBuilder sb = new StringBuilder("<<");
        List<SmithyPattern.Segment> segments = hostPrefix.getSegments();
        for (int i = 0; i < segments.size(); i++) {
            SmithyPattern.Segment segment = segments.get(i);
            if (segment.isLabel()) {
                String fieldName = BeamNameUtils.toSnakeCase(segment.getContent());
                sb.append("(uri_encode(to_binary(")
                        .append(toBindingVar(fieldName))
                        .append(")))/binary");
            } else {
                sb.append("\"").append(segment.getContent()).append("\"");
            }
            if (i < segments.size() - 1) {
                sb.append(", ");
            }
        }
        sb.append(">>");
        return sb.toString();
    }

    private static void emitFlattenBindingCases(
            ErlangWriter writer,
            Model model,
            SymbolProvider sp,
            List<HttpBinding> bindings,
            boolean queryValues) {
        writer.write("lists:flatten([");
        for (int i = 0; i < bindings.size(); i++) {
            HttpBinding binding = bindings.get(i);
            String fieldVar = toBindingVar(
                    BeamNameUtils.toSnakeCase(binding.getMember().getMemberName()));
            String valueVar = fieldVar + "Val";
            String encodedValue = encodeBindingWireValue(model, sp, binding.getMember(), valueVar, queryValues);
            String suffix = i < bindings.size() - 1 ? "," : "";
            writer.write("  case $L of undefined -> []; $L -> [{<<\"$L\">>, $L}] end$L",
                    fieldVar, valueVar, binding.getLocationName(), encodedValue, suffix);
        }
        writer.write("]),");
    }

    private static void emitHeaderBindingDecode(
            ErlangWriter writer,
            Model model,
            SymbolProvider sp,
            HttpBinding binding) {
        String fieldName = BeamNameUtils.toSnakeCase(binding.getMember().getMemberName());
        String bindingVar = toBindingVar(fieldName);
        String headerLookup = "proplists:get_value(<<\"" + binding.getLocationName() + "\">>, Headers, undefined)";
        Shape target = model.expectShape(binding.getMember().getTarget());
        if (target instanceof EnumShape || target instanceof IntEnumShape) {
            String helperName = sp.toSymbol(target).getName().replace("()", "");
            writer.write("$L = decode_$L($L),", bindingVar, helperName, headerLookup);
        } else {
            writer.write("$L = $L,", bindingVar, headerLookup);
        }
    }

    private static String encodeBindingWireValue(
            Model model,
            SymbolProvider sp,
            MemberShape member,
            String valueVar,
            boolean queryValues) {
        Shape target = model.expectShape(member.getTarget());
        if (target instanceof EnumShape || target instanceof IntEnumShape) {
            String helperName = sp.toSymbol(target).getName().replace("()", "");
            return "encode_" + helperName + "(" + valueVar + ")";
        }
        if (queryValues) {
            return "encode_query_value(" + valueVar + ")";
        }
        return "to_binary(" + valueVar + ")";
    }

    private static void emitEnumHelpers(
            ErlangWriter writer, Model model, ServiceShape service, SymbolProvider sp) {

        Set<ShapeId> emitted = new LinkedHashSet<>();
        for (Shape shape : new Walker(model).walkShapes(service)) {
            if (shape instanceof EnumShape enumShape) {
                if (emitted.add(enumShape.getId())) {
                    emitEnumDecodeEncode(writer, enumShape, sp);
                }
            } else if (shape instanceof IntEnumShape intEnumShape) {
                if (emitted.add(intEnumShape.getId())) {
                    emitIntEnumDecodeEncode(writer, intEnumShape, sp);
                }
            }
        }
    }

    private static void emitEnumDecodeEncode(ErlangWriter writer, EnumShape shape, SymbolProvider sp) {
        String helperName = sp.toSymbol(shape).getName().replace("()", "");
        writer.write("%% Enum helpers for $L", shape.getId());
        for (MemberShape m : shape.members()) {
            String wireValue = m.getTrait(EnumValueTrait.class)
                    .flatMap(EnumValueTrait::getStringValue)
                    .orElse(m.getMemberName());
            String atom = enumAtomForMember(sp, shape, m.getMemberName());
            writer.write("decode_$L(<<\"$L\">>) -> $L;", helperName, wireValue, atom);
        }
        writer.write("decode_$L(V) when is_binary(V) -> {unknown, V};", helperName);
        writer.write("decode_$L(null) -> undefined;", helperName);
        writer.write("decode_$L(undefined) -> undefined.", helperName);
        writer.write("");
        for (MemberShape m : shape.members()) {
            String wireValue = m.getTrait(EnumValueTrait.class)
                    .flatMap(EnumValueTrait::getStringValue)
                    .orElse(m.getMemberName());
            String atom = enumAtomForMember(sp, shape, m.getMemberName());
            writer.write("encode_$L($L) -> <<\"$L\">>;", helperName, atom, wireValue);
        }
        writer.write("encode_$L({unknown, V}) when is_binary(V) -> V;", helperName);
        writer.write("encode_$L(undefined) -> undefined.", helperName);
        writer.write("");
    }

    private static void emitIntEnumDecodeEncode(ErlangWriter writer, IntEnumShape shape, SymbolProvider sp) {
        String helperName = sp.toSymbol(shape).getName().replace("()", "");
        writer.write("%% IntEnum helpers for $L", shape.getId());
        for (MemberShape m : shape.members()) {
            int wireValue = m.expectTrait(EnumValueTrait.class).expectIntValue();
            String atom = enumAtomForMember(sp, shape, m.getMemberName());
            writer.write("decode_$L($L) -> $L;", helperName, wireValue, atom);
        }
        writer.write("decode_$L(V) when is_integer(V) -> {unknown, V};", helperName);
        writer.write("decode_$L(null) -> undefined;", helperName);
        writer.write("decode_$L(undefined) -> undefined.", helperName);
        writer.write("");
        for (MemberShape m : shape.members()) {
            int wireValue = m.expectTrait(EnumValueTrait.class).expectIntValue();
            String atom = enumAtomForMember(sp, shape, m.getMemberName());
            writer.write("encode_$L($L) -> $L;", helperName, atom, wireValue);
        }
        writer.write("encode_$L({unknown, V}) when is_integer(V) -> V;", helperName);
        writer.write("encode_$L(undefined) -> undefined.", helperName);
        writer.write("");
    }

    private static String enumAtomForMember(SymbolProvider sp, Shape enumShape, String memberName) {
        @SuppressWarnings("unchecked")
        Map<String, String> byMember = sp.toSymbol(enumShape)
                .getProperty("enumAtomByMember", Map.class)
                .orElseThrow();
        return byMember.get(memberName);
    }

    private static String resolvedRequestContentType(
            Model model, OperationShape op, List<HttpBinding> payloadMembers) {
        if (!payloadMembers.isEmpty()) {
            MemberShape member = payloadMembers.get(0).getMember();
            Shape target = model.expectShape(member.getTarget());
            Optional<String> mediaType = member.getTrait(MediaTypeTrait.class)
                    .map(MediaTypeTrait::getValue);
            if (mediaType.isPresent()) {
                return mediaType.get();
            }
            if (target instanceof BlobShape) {
                return "application/octet-stream";
            }
            if (target instanceof StringShape) {
                return "text/plain";
            }
        }
        return BeamHttpBindings.from(model)
                .requestContentType(op, DEFAULT_CONTENT_TYPE)
                .orElse(DEFAULT_CONTENT_TYPE);
    }
