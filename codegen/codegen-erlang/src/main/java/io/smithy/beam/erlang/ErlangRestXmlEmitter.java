    private static void emitEncoder(
            ErlangWriter writer,
            Model model,
            ServiceShape service,
            OperationShape op,
            HttpBindingIndex httpIndex,
            SymbolProvider sp,
            boolean encodeWithConfig) {

        String opName = sp.toSymbol(op).getName();
        StructureShape input = model.expectShape(op.getInputShape(), StructureShape.class);
        String inputRecord = recordName(sp.toSymbol(input));
        String inputType = sp.toSymbol(input).getName();
        HttpTrait httpTrait = op.expectTrait(HttpTrait.class);
        String method = httpTrait.getMethod();
        String uriTemplate = httpTrait.getUri().toString();

        List<HttpBinding> labels = httpIndex.getRequestBindings(op, HttpBinding.Location.LABEL);
        List<HttpBinding> queries = httpIndex.getRequestBindings(op, HttpBinding.Location.QUERY);
        List<HttpBinding> queryParams = httpIndex.getRequestBindings(op, HttpBinding.Location.QUERY_PARAMS);
        List<HttpBinding> headers = httpIndex.getRequestBindings(op, HttpBinding.Location.HEADER);
        List<HttpBinding> prefixHeaders = httpIndex.getRequestBindings(op, HttpBinding.Location.PREFIX_HEADERS);
        List<HttpBinding> payloadMembers = httpIndex.getRequestBindings(op, HttpBinding.Location.PAYLOAD);

        String requestContentType = resolvedRequestContentType(model, op, payloadMembers);

        List<String> patternParts = buildPatternParts(labels, queries, queryParams, headers, prefixHeaders, payloadMembers);
        String pattern = patternParts.isEmpty() ? "" : "\n    " + String.join(",\n    ", patternParts) + "\n";

        writer.write("%% Encode REST-XML request for $L.", op.getId());
        if (encodeWithConfig) {
            ErlangFormat.writeSpec(
                    writer,
                    "encode_" + opName + "_request(client_config(), " + inputType + ") -> #http_request{}");
            writer.write("encode_$L_request(Config, Input = #$L{$L}) ->", opName, inputRecord, pattern);
        } else {
            ErlangFormat.writeSpec(writer, "encode_" + opName + "_request(" + inputType + ") -> #http_request{}");
            writer.write("encode_$L_request(Input = #$L{$L}) ->", opName, inputRecord, pattern);
        }
        writer.indent();

        List<MemberShape> idempotencyMembers = input.members().stream()
                .filter(m -> m.hasTrait(IdempotencyTokenTrait.class))
                .collect(Collectors.toList());
        if (!idempotencyMembers.isEmpty()) {
            String currentInput = "Input";
            int step = 1;
            for (MemberShape member : idempotencyMembers) {
                String field = BeamNameUtils.toSnakeCase(member.getMemberName());
                String nextInput = "Input" + step;
                writer.write("$L = case $L#$L.$L of", nextInput, currentInput, inputRecord, field);
                writer.indent();
                writer.write("undefined -> $L#$L{ $L = generate_uuid() };", currentInput, inputRecord, field);
                writer.write("_ -> $L", currentInput);
                writer.dedent();
                writer.write("end,");
                currentInput = nextInput;
                step++;
            }
            for (MemberShape member : idempotencyMembers) {
                String field = BeamNameUtils.toSnakeCase(member.getMemberName());
                writer.write("$L = $L#$L.$L,", toBindingVar(field), currentInput, inputRecord, field);
            }
        }

        BeamHostLabelIndex hostLabelIndex = BeamHostLabelIndex.of(model);
        boolean hasHostLabels = !hostLabelIndex.hostLabelMembers(op).isEmpty()
                && op.hasTrait(EndpointTrait.class);
        BeamS3CustomizationIndex s3Index = BeamS3CustomizationIndex.of(model);
        boolean s3BucketAddressing = s3Index.isS3Service(service)
                && s3Index.bucketLabelBinding(op).isPresent();

        if (s3BucketAddressing) {
            String bucketVar = toBindingVar(s3Index.bucketMemberSnakeCase(op));
            String keyVar = s3Index.keyMemberSnakeCase(op)
                    .map(ErlangRestXmlEmitter::toBindingVar)
                    .orElse("<<>>");
            if (encodeWithConfig) {
                writer.write("{Host, Path} = s3_endpoint:resolve_bucket_url(Config, $L, $L),",
                        bucketVar, keyVar);
            } else {
                writer.write("{Host, Path} = s3_endpoint:resolve_bucket_url(#{}, $L, $L),",
                        bucketVar, keyVar);
            }
        } else {
            String pathExpr = buildPathExpression(uriTemplate, labels);
            writer.write("Path = $L,", pathExpr);
        }

        if (queries.isEmpty()) {
            writer.write("Query = [],");
        } else {
            writer.write("Query = ");
            emitFlattenBindingCases(writer, model, sp, queries, true);
        }

        if (!queryParams.isEmpty()) {
            for (HttpBinding qp : queryParams) {
                String fieldName = BeamNameUtils.toSnakeCase(qp.getMember().getMemberName());
                String bindingVar = toBindingVar(fieldName);
                writer.write("QueryExtra = case $L of", bindingVar);
                writer.indent();
                writer.write("undefined -> [];");
                writer.write("M when is_map(M) ->");
                writer.indent();
                writer.write("[{K, V} || {K, V} <- maps:to_list(M)]");
                writer.dedent();
                writer.dedent();
                writer.write("end,");
                writer.write("Query = Query ++ QueryExtra,");
            }
        }

        if (headers.isEmpty()) {
            writer.write("Headers = [{<<\"Content-Type\">>, <<\"$L\">>}],", requestContentType);
        } else {
            writer.write("Headers0 = ");
            emitFlattenBindingCases(writer, model, sp, headers, false);
            writer.write("Headers = [{<<\"Content-Type\">>, <<\"$L\">>} | Headers0],", requestContentType);
        }

        for (HttpBinding ph : prefixHeaders) {
            String fieldName = BeamNameUtils.toSnakeCase(ph.getMember().getMemberName());
            String prefix = ph.getLocationName();
            writer.write("Headers = Headers ++ prefix_headers_to_list(<<\"$L\">>, $L),",
                    prefix, toBindingVar(fieldName));
        }

        emitRequestBody(writer, model, payloadMembers, method, sp);
        Optional<String> headersWithChecksum =
                ErlangHttpChecksumEmitter.emitRequestChecksumHeaders(writer, model, op, sp, "Headers");
        String requestHeaders = headersWithChecksum.orElse("Headers");

        if (hasHostLabels && !s3BucketAddressing) {
            writer.write("Host = build_host(Input, Config),");
        }

        writer.write("#http_request{");
        writer.write("    method = <<\"$L\">>,", method);
        writer.write("    path = Path,");
        writer.write("    query = maps:from_list(Query),");
        writer.write("    headers = $L,", requestHeaders);
        writer.write("    body = Body");
        if (hasHostLabels || s3BucketAddressing) {
            writer.write("    ,host = Host");
        }
        writer.write("}.");
        writer.dedent();
        writer.write("");
    }

    private static void emitRequestBody(
            ErlangWriter writer,
            Model model,
            List<HttpBinding> payloadMembers,
            String method,
            SymbolProvider sp) {

        if (payloadMembers.isEmpty()
                || method.equals("GET")
                || method.equals("DELETE")
                || method.equals("HEAD")) {
            writer.write("Body = <<>>,");
            return;
        }

        HttpBinding payload = payloadMembers.get(0);
        MemberShape member = payload.getMember();
        Shape target = model.expectShape(member.getTarget());
        String fieldName = BeamNameUtils.toSnakeCase(member.getMemberName());
        String bindingVar = toBindingVar(fieldName);

        if (target instanceof BlobShape || target instanceof StringShape) {
            writer.write("Body = case $L of", bindingVar);
            writer.indent();
            writer.write("undefined -> <<>>;");
            writer.write("Value -> Value");
            writer.dedent();
            writer.write("end,");
            return;
        }

        String rootElement = BeamXmlBindingIndex.payloadRootElementName(member, target);
        writer.write("XmlNs = xml_namespace(),");
        writer.write("Body = case $L of", bindingVar);
        writer.indent();
        writer.write("undefined -> <<>>;");
        writer.write("PayloadValue ->");
        writer.indent();
        if (target instanceof StructureShape structure) {
            writer.write("MemberMap = $L,",
                    buildStructureXmlMap(model, structure, "PayloadValue", recordName(sp.toSymbol(structure))));
            writer.write("Payload = encode_xml(#{<<\"$L\">> => MemberMap}, XmlNs),", rootElement);
        } else if (target instanceof UnionShape union) {
            writer.write("Payload =");
            writer.indent();
            emitUnionPayloadEncode(writer, model, union, rootElement, "PayloadValue", sp);
            writer.write(",");
            writer.dedent();
        } else {
            writer.write("Payload = encode_xml(#{<<\"$L\">> => PayloadValue}, XmlNs),", rootElement);
        }
        writer.write("Payload");
        writer.dedent();
        writer.dedent();
        writer.write("end,");
    }

    private static String buildStructureXmlMap(
            Model model, StructureShape structure, String recordVar, String recordTag) {
        List<String> entries = new ArrayList<>();
        for (MemberShape member : structure.members()) {
            if (BeamXmlBindingIndex.isXmlAttribute(member)) {
                continue;
            }
            String field = BeamNameUtils.toSnakeCase(member.getMemberName());
            String wireName = BeamXmlBindingIndex.memberElementName(member);
            entries.add("<<\"" + wireName + "\">> => " + recordVar + "#" + recordTag + "." + field);
        }
        if (entries.isEmpty()) {
            return "#{}" ;
        }
        return "#{" + String.join(", ", entries) + "}";
    }

