package io.smithy.beam.erlang;

import io.smithy.beam.core.BeamAwsQueryFormEncoder;
import io.smithy.beam.core.BeamAwsServiceMetadata;
import io.smithy.beam.core.BeamErlangLayout;
import io.smithy.beam.core.BeamNameUtils;
import software.amazon.smithy.codegen.core.SymbolProvider;
import software.amazon.smithy.model.Model;
import software.amazon.smithy.model.knowledge.HttpBindingIndex;
import software.amazon.smithy.model.shapes.MemberShape;
import software.amazon.smithy.model.shapes.OperationShape;
import software.amazon.smithy.model.shapes.ServiceShape;
import software.amazon.smithy.model.shapes.StructureShape;
import software.amazon.smithy.model.traits.XmlNameTrait;

import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;

/**
 * AWS Query protocol codec emitter for Erlang clients. POST / with form-urlencoded body.
 */
public final class ErlangAwsQueryEmitter {

    private static final String CONTENT_TYPE = "application/x-www-form-urlencoded";

    private ErlangAwsQueryEmitter() {}

    static void emitCodecModule(ErlangContext ctx, ServiceShape service) {
        BeamAwsServiceMetadata.from(service).orElseThrow();
        Model model = ctx.model();
        BeamErlangLayout layout = new BeamErlangLayout(
                ctx.settings(), service.getId().getNamespace(), service);
        String codecFile = layout.clientCodecModuleName(
                io.smithy.beam.core.BeamAwsQueryProtocolCodegen.AWS_QUERY) + ".erl";
        String codecModule = layout.clientCodecModuleName(
                io.smithy.beam.core.BeamAwsQueryProtocolCodegen.AWS_QUERY);
        HttpBindingIndex httpIndex = HttpBindingIndex.of(model);
        SymbolProvider sp = ctx.symbolProvider();

        List<OperationShape> operations = ErlangTopDown.containedOperationsSorted(model, service);
        List<String> exports = new ArrayList<>();
        for (OperationShape op : operations) {
            String name = sp.toSymbol(op).getName();
            exports.add("encode_" + name + "_request/1");
        }

        Set<StructureShape> inputShapes = new LinkedHashSet<>();
        for (OperationShape op : operations) {
            inputShapes.add(model.expectShape(op.getInputShape(), StructureShape.class));
        }

        ctx.writerDelegator().useFileWriter(codecFile, writer -> {
            writer.write("%% AWS Query codecs for $L (generated).", service.getId());
            writer.write("%% DO NOT EDIT -- generated by smithy-beam codegen.");
            writer.write("-module($L).", codecModule);
            writer.write("-include(\"$L\").", layout.typesHeaderFile());
            writer.write("-include(\"$L\").", layout.runtimeTypesHeaderFile());
            writer.write("-export([$L]).", String.join(", ", exports));
            writer.write("");

            for (OperationShape op : operations) {
                emitEncoder(writer, model, service, op, httpIndex, sp);
            }

            for (StructureShape input : inputShapes) {
                emitFlattenInputClause(writer, model, httpIndex, sp, input);
            }

            emitQueryHelpers(writer);
        });
    }

    private static void emitEncoder(
            ErlangWriter writer,
            Model model,
            ServiceShape service,
            OperationShape op,
            HttpBindingIndex httpIndex,
            SymbolProvider sp) {

        String opName = sp.toSymbol(op).getName();
        StructureShape input = model.expectShape(op.getInputShape(), StructureShape.class);
        String inputRecord = recordName(sp.toSymbol(input));
        String inputType = sp.toSymbol(input).getName();
        String action = BeamAwsQueryFormEncoder.operationAction(op, service);
        String version = BeamAwsQueryFormEncoder.serviceVersion(service);
        String pattern = inputPattern(input);

        writer.write("%% Encode AWS Query request for $L.", op.getId());
        writer.write("-spec encode_$L_request($L) -> #http_request{}.", opName, inputType);
        writer.write("encode_$L_request(Input = #$L{$L}) ->", opName, inputRecord, pattern);
        writer.indent();
        writer.write("Pairs = [");
        writer.write("    {<<\"Action\">>, <<\"$L\">>},", action);
        writer.write("    {<<\"Version\">>, <<\"$L\">>}", version);
        writer.write("    | flatten_query_input(Input)");
        writer.write("],");
        writer.write("Body = uri_string:compose_query([{K, enc(V)} || {K, V} <- Pairs, V =/= undefined]),");
        writer.write("#http_request{");
        writer.write("    method = <<\"POST\">>,");
        writer.write("    path = <<\"/\">>,");
        writer.write("    query = #{},");
        writer.write("    headers = [{<<\"Content-Type\">>, <<\"$L\">>}],", CONTENT_TYPE);
        writer.write("    body = Body");
        writer.write("}.");
        writer.dedent();
        writer.write("");
    }

    private static void emitFlattenInputClause(
            ErlangWriter writer,
            Model model,
            HttpBindingIndex httpIndex,
            SymbolProvider sp,
            StructureShape input) {

        String inputRecord = recordName(sp.toSymbol(input));
        List<MemberShape> members = documentMembers(httpIndex, input);

        writer.write("flatten_query_input(#$L{", inputRecord);
        for (int i = 0; i < members.size(); i++) {
            MemberShape member = members.get(i);
            String field = BeamNameUtils.toSnakeCase(member.getMemberName());
            if (i < members.size() - 1) {
                writer.write("    $L = $L,", field, toBindingVar(field));
            } else {
                writer.write("    $L = $L", field, toBindingVar(field));
            }
        }
        writer.write("}) ->");
        writer.indent();
        if (members.isEmpty()) {
            writer.write("[].");
        } else {
            writer.write("lists:append([");
            for (int i = 0; i < members.size(); i++) {
                MemberShape member = members.get(i);
                String field = BeamNameUtils.toSnakeCase(member.getMemberName());
                String wireKey = queryFormKey(member);
                if (i < members.size() - 1) {
                    writer.write("    flatten_member(<<\"$L\">>, $L),", wireKey, toBindingVar(field));
                } else {
                    writer.write("    flatten_member(<<\"$L\">>, $L)", wireKey, toBindingVar(field));
                }
            }
            writer.write("]).");
        }
        writer.dedent();
        writer.write("");
    }

    private static void emitQueryHelpers(ErlangWriter writer) {
        writer.write("flatten_member(_Key, undefined) ->");
        writer.indent();
        writer.write("[].");
        writer.dedent();
        writer.write("flatten_member(Key, Value) when is_list(Value) ->");
        writer.indent();
        writer.write("lists:append([");
        writer.write("    flatten_member(");
        writer.write("        <<Key/binary, \".member.\", (integer_to_binary(I))/binary>>,");
        writer.write("        V");
        writer.write("    )");
        writer.write("    || {I, V} <- lists:enumerate(Value), V =/= undefined");
        writer.write("]).");
        writer.dedent();
        writer.write("flatten_member(Key, Value) when is_map(Value) ->");
        writer.indent();
        writer.write("lists:append([");
        writer.write("    flatten_member(<<Key/binary, \".entry.\", (integer_to_binary(I))/binary, \".key\">>, K)");
        writer.write("    ++ flatten_member(<<Key/binary, \".entry.\", (integer_to_binary(I))/binary, \".value\">>, V)");
        writer.write("    || {I, {K, V}} <- lists:enumerate(maps:to_list(Value)),");
        writer.write("       K =/= undefined, V =/= undefined");
        writer.write("]).");
        writer.dedent();
        writer.write("flatten_member(Key, Value) when is_tuple(Value) ->");
        writer.indent();
        writer.write("flatten_structure(Key, Value);");
        writer.dedent();
        writer.write("flatten_member(Key, Value) ->");
        writer.indent();
        writer.write("[{Key, Value}].");
        writer.dedent();
        writer.write("");
        writer.write("flatten_structure(_Key, undefined) ->");
        writer.indent();
        writer.write("[].");
        writer.dedent();
        writer.write("flatten_structure(_Key, _Value) ->");
        writer.indent();
        writer.write("[].");
        writer.dedent();
        writer.write("");
        writer.write("enc(V) when is_boolean(V) ->");
        writer.indent();
        writer.write("atom_to_binary(V, utf8);");
        writer.dedent();
        writer.write("enc(V) when is_integer(V) ->");
        writer.indent();
        writer.write("integer_to_binary(V);");
        writer.dedent();
        writer.write("enc(V) when is_float(V) ->");
        writer.indent();
        writer.write("float_to_binary(V);");
        writer.dedent();
        writer.write("enc(V) when is_binary(V) ->");
        writer.indent();
        writer.write("V;");
        writer.dedent();
        writer.write("enc(V) when is_atom(V) ->");
        writer.indent();
        writer.write("atom_to_binary(V, utf8).");
        writer.dedent();
        writer.write("");
    }

    private static List<MemberShape> documentMembers(HttpBindingIndex httpIndex, StructureShape structure) {
        return new ArrayList<>(structure.members());
    }

    private static String queryFormKey(MemberShape member) {
        return member.getTrait(XmlNameTrait.class)
                .map(XmlNameTrait::getValue)
                .orElseGet(() -> capitalizeFirst(member.getMemberName()));
    }

    private static String capitalizeFirst(String name) {
        if (name.isEmpty()) {
            return name;
        }
        return Character.toUpperCase(name.charAt(0)) + name.substring(1);
    }

    private static String recordName(software.amazon.smithy.codegen.core.Symbol symbol) {
        return symbol.getName().replace("()", "");
    }

    private static String toBindingVar(String snakeField) {
        return BeamNameUtils.toCamelCaseVariable(snakeField);
    }

    private static String inputPattern(StructureShape input) {
        List<String> parts = new ArrayList<>();
        for (MemberShape member : input.members()) {
            String field = BeamNameUtils.toSnakeCase(member.getMemberName());
            parts.add(field + " = " + toBindingVar(field));
        }
        return parts.isEmpty() ? "" : "\n    " + String.join(",\n    ", parts) + "\n";
    }
}
