    private static void emitQueryHelpers(ErlangWriter writer, boolean ec2Query) {
        writer.write("flatten_member(_Key, undefined) ->");
        writer.indent();
        writer.write("[];");
        writer.dedent();
        if (ec2Query) {
            writer.write("flatten_member(Key, Value) when is_list(Value) ->");
            writer.indent();
            writer.write("lists:append([");
            writer.write("    flatten_member(");
            writer.write("        <<Key/binary, \".\", (integer_to_binary(I))/binary>>,");
            writer.write("        V");
            writer.write("    )");
            writer.write("    || {I, V} <- lists:enumerate(Value), V =/= undefined");
            writer.write("]);");
            writer.dedent();
        } else {
            writer.write("flatten_member(Key, Value) when is_list(Value) ->");
            writer.indent();
            writer.write("lists:append([");
            writer.write("    flatten_member(");
            writer.write("        <<Key/binary, \".member.\", (integer_to_binary(I))/binary>>,");
            writer.write("        V");
            writer.write("    )");
            writer.write("    || {I, V} <- lists:enumerate(Value), V =/= undefined");
            writer.write("]);");
            writer.dedent();
        }
        writer.write("flatten_member(Key, Value) when is_map(Value) ->");
        writer.indent();
        writer.write("lists:append([");
        writer.write("    flatten_member(<<Key/binary, \".entry.\", (integer_to_binary(I))/binary, \".key\">>, K)");
        writer.write("    ++ flatten_member(<<Key/binary, \".entry.\", (integer_to_binary(I))/binary, \".value\">>, V)");
        writer.write("    || {I, {K, V}} <- lists:enumerate(maps:to_list(Value)),");
        writer.write("       K =/= undefined, V =/= undefined");
        writer.write("]);");
        writer.dedent();
        writer.write("flatten_member(Key, Value) when is_tuple(Value) ->");
        writer.indent();
        writer.write("flatten_structure(Key, Value);");
        writer.dedent();
        writer.write("flatten_member(Key, Value) ->");
        writer.indent();
        writer.write("[{Key, Value}].");
        writer.dedent();
        writer.write("");
        writer.write("flatten_structure(_Key, undefined) ->");
        writer.indent();
        writer.write("[];");
        writer.dedent();
        writer.write("flatten_structure(_Key, _Value) ->");
        writer.indent();
        writer.write("[].");
        writer.dedent();
        writer.write("");
        writer.write("enc(V) when is_boolean(V) ->");
        writer.indent();
        writer.write("atom_to_binary(V, utf8);");
        writer.dedent();
        writer.write("enc(V) when is_integer(V) ->");
        writer.indent();
        writer.write("integer_to_binary(V);");
        writer.dedent();
        writer.write("enc(V) when is_float(V) ->");
        writer.indent();
        writer.write("float_to_binary(V);");
        writer.dedent();
        writer.write("enc(V) when is_binary(V) ->");
        writer.indent();
        writer.write("V;");
        writer.dedent();
        writer.write("enc(V) when is_atom(V) ->");
        writer.indent();
        writer.write("atom_to_binary(V, utf8).");
        writer.dedent();
        writer.write("");
    }

