    private static void emitBuildHostHelpers(
            ErlangWriter writer,
            Model model,
            ServiceShape service,
            SymbolProvider sp) {

        writer.write("%% Host label helpers for @endpoint hostPrefix expansion.");
        writer.write("split_base_url(<<>>) ->");
        writer.indent();
        writer.write("{<<>>, <<>>};");
        writer.dedent();
        writer.write("split_base_url(BaseUrl) ->");
        writer.indent();
        writer.write("case uri_string:parse(binary_to_list(BaseUrl)) of");
        writer.indent();
        writer.write("#{scheme := Scheme, host := Host} = Parts ->");
        writer.indent();
        writer.write("PortSuffix = case maps:get(port, Parts, undefined) of");
        writer.indent();
        writer.write("undefined -> <<>>;");
        writer.write("Port -> <<\":\", (integer_to_binary(Port))/binary>>");
        writer.dedent();
        writer.write("end,");
        writer.write("{<< (list_to_binary(Scheme))/binary, \"://\">>,");
        writer.write(" << (list_to_binary(Host))/binary, PortSuffix/binary >>};");
        writer.dedent();
        writer.write("_ ->");
        writer.indent();
        writer.write("{<<>>, BaseUrl}");
        writer.dedent();
        writer.dedent();
        writer.write("end.");
        writer.dedent();
        writer.write("");

        BeamHostLabelIndex hostLabelIndex = BeamHostLabelIndex.of(model);
        for (OperationShape op : ErlangTopDown.containedOperationsSorted(model, service)) {
            List<MemberShape> hostLabels = hostLabelIndex.hostLabelMembers(op);
            if (hostLabels.isEmpty() || !op.hasTrait(EndpointTrait.class)) {
                continue;
            }
            StructureShape input = model.expectShape(op.getInputShape(), StructureShape.class);
            String inputRecord = recordName(sp.toSymbol(input));
            SmithyPattern hostPrefix = op.expectTrait(EndpointTrait.class).getHostPrefix();
            String prefixExpr = buildHostPrefixExpression(hostPrefix);
            List<String> patternParts = hostLabels.stream()
                    .map(m -> {
                        String field = BeamNameUtils.toSnakeCase(m.getMemberName());
                        return field + " = " + toBindingVar(field);
                    })
                    .toList();
            String pattern = patternParts.isEmpty()
                    ? "" : "\n    " + String.join(",\n    ", patternParts) + "\n";

            writer.write("build_host(#$L{$L}, Config) ->", inputRecord, pattern);
            writer.indent();
            writer.write("BaseUrl = maps:get(base_url, Config, <<>>),");
            writer.write("{_Scheme, Authority} = split_base_url(BaseUrl),");
            writer.write("Prefix = $L,", prefixExpr);
            writer.write("<<Prefix/binary, Authority/binary>>.");
            writer.dedent();
            writer.write("");
        }
    }

    public static boolean serviceHasHostLabelOperations(Model model, ServiceShape service) {
        BeamHostLabelIndex hostLabelIndex = BeamHostLabelIndex.of(model);
        for (OperationShape op : ErlangTopDown.containedOperationsSorted(model, service)) {
            if (!hostLabelIndex.hostLabelMembers(op).isEmpty() && op.hasTrait(EndpointTrait.class)) {
                return true;
            }
        }
        return false;
    }

    private static String buildHostPrefixExpression(SmithyPattern hostPrefix) {
        if (hostPrefix.getSegments().isEmpty()) {
            return "<<>>";
        }
        StringBuilder sb = new StringBuilder("<<");
        List<SmithyPattern.Segment> segments = hostPrefix.getSegments();
        for (int i = 0; i < segments.size(); i++) {
            SmithyPattern.Segment segment = segments.get(i);
            if (segment.isLabel()) {
                String memberName = segment.getContent();
                String fieldName = BeamNameUtils.toSnakeCase(memberName);
                sb.append("(uri_encode(to_binary(")
                        .append(toBindingVar(fieldName))
                        .append(")))/binary");
            } else {
                sb.append("\"").append(segment.getContent()).append("\"");
            }
            if (i < segments.size() - 1) {
                sb.append(", ");
            }
        }
        sb.append(">>");
        return sb.toString();
    }

    /** Record tag for #-record{} syntax; symbol names carry a trailing {@code ()} type suffix. */
    private static String recordName(Symbol symbol) {
        return symbol.getName().replace("()", "");
    }

    private static List<String> buildPatternParts(
            List<HttpBinding> labels,
            List<HttpBinding> queries,
            List<HttpBinding> queryParams,
            List<HttpBinding> headers,
            List<HttpBinding> prefixHeaders,
            List<HttpBinding> docMembers,
            List<HttpBinding> reqPayload,
            SymbolProvider sp,
            Model model) {
        List<String> parts = new ArrayList<>();
        for (HttpBinding b : concat(labels, queries, queryParams, headers, prefixHeaders, docMembers, reqPayload)) {
            String field = BeamNameUtils.toSnakeCase(b.getMember().getMemberName());
            parts.add(field + " = " + toBindingVar(field));
        }
        return parts;
    }

    private static void emitRequestBody(
            ErlangWriter writer,
            Model model,
            HttpBindingIndex httpIndex,
            List<HttpBinding> reqPayload,
            List<HttpBinding> docMembers,
            String method,
            SymbolProvider sp,
            String eventStreamModule) {

        if (!reqPayload.isEmpty()
                && !method.equals("GET")
                && !method.equals("DELETE")
                && !method.equals("HEAD")) {
            HttpBinding payload = reqPayload.get(0);
            MemberShape member = payload.getMember();
            String fieldName = BeamNameUtils.toSnakeCase(member.getMemberName());
            String bindingVar = toBindingVar(fieldName);
            if (isStreamingBlob(model, member)) {
                writer.write("Body = <<>>,");
                return;
            }
            if (BeamEventStreamIndex.of(model).isEventStreamMember(member)) {
                UnionShape union = model.expectShape(member.getTarget(), UnionShape.class);
                String helper = ErlangEventStreamEmitter.helperName(sp, union);
                writer.write("Body = iolist_to_binary($L:encode_$L($L)),",
                        eventStreamModule, helper, bindingVar);
                return;
            }
            Shape target = model.expectShape(member.getTarget());
            if (target instanceof BlobShape || target instanceof StringShape) {
                writer.write("Body = case $L of", bindingVar);
                writer.indent();
                writer.write("undefined -> <<>>;");
                writer.write("Value -> Value");
                writer.dedent();
                writer.write("end,");
                return;
            }
        }

        if (docMembers.isEmpty() || method.equals("GET") || method.equals("DELETE") || method.equals("HEAD")) {
            writer.write("Body = <<>>,");
        } else {
            writer.write("BodyMap = maps:filter(fun(_, V) -> V =/= undefined end, #{");
            for (int i = 0; i < docMembers.size(); i++) {
                HttpBinding db = docMembers.get(i);
                String fieldName = BeamNameUtils.toSnakeCase(db.getMember().getMemberName());
                String wireKey = jsonKey(db.getMember());
                String comma = i < docMembers.size() - 1 ? "," : "";
                Shape target = model.expectShape(db.getMember().getTarget());
                if (target instanceof EnumShape || target instanceof IntEnumShape) {
                    String helperName = sp.toSymbol(target).getName().replace("()", "");
                    writer.write("    <<\"$L\">> => encode_$L($L)$L",
                            wireKey, helperName, toBindingVar(fieldName), comma);
                } else if (target instanceof UnionShape) {
                    String helperName = sp.toSymbol(target).getName().replace("()", "");
                    writer.write("    <<\"$L\">> => encode_$L($L)$L",
                            wireKey, helperName, toBindingVar(fieldName), comma);
                } else if (target instanceof TimestampShape) {
                    String encodeHelper = timestampEncodeHelper(
                            httpIndex, db.getMember(), HttpBinding.Location.DOCUMENT);
                    writer.write("    <<\"$L\">> => $L($L)$L",
                            wireKey, encodeHelper, toBindingVar(fieldName), comma);
                } else {
                    writer.write("    <<\"$L\">> => $L$L",
                            wireKey,
                            ErlangJsonCodecSupport.encodeDocumentValue(
                                    model, sp, httpIndex, db.getMember(), fieldName),
                            comma);
                }
            }
            writer.write("}),");
            writer.write("Body = jsone:encode(BodyMap),");
        }
    }

    private static boolean hasStreamingRequestPayload(
            Model model, List<HttpBinding> reqPayload, String method) {
        if (reqPayload.isEmpty()) {
            return false;
        }
        if (method != null
                && (method.equals("GET") || method.equals("DELETE") || method.equals("HEAD"))) {
            return false;
        }
        return isStreamingBlob(model, reqPayload.get(0).getMember());
    }

    private static boolean isStreamingBlob(Model model, MemberShape member) {
        Shape target = model.expectShape(member.getTarget());
        return target instanceof BlobShape && target.hasTrait(StreamingTrait.class);
    }

    /** Erlang variable for a snake_case record field (Inaka CamelCase, no underscores). */
    private static String toBindingVar(String snakeField) {
        return BeamNameUtils.toCamelCaseVariable(snakeField);
    }

    private static String jsonKey(MemberShape member) {
        return member.getTrait(JsonNameTrait.class)
                .map(JsonNameTrait::getValue)
                .orElse(member.getMemberName());
    }

    private static String timestampEncodeHelper(
            HttpBindingIndex httpIndex, MemberShape member, HttpBinding.Location location) {
        TimestampFormatTrait.Format fmt = httpIndex.determineTimestampFormat(
                member, location, TimestampFormatTrait.Format.DATE_TIME);
        return fmt == TimestampFormatTrait.Format.EPOCH_SECONDS
                ? "encode_timestamp_epoch_seconds"
                : "encode_timestamp_date_time";
    }

    private static String timestampDecodeHelper(
            HttpBindingIndex httpIndex, MemberShape member, HttpBinding.Location location) {
        TimestampFormatTrait.Format fmt = httpIndex.determineTimestampFormat(
                member, location, TimestampFormatTrait.Format.DATE_TIME);
        return fmt == TimestampFormatTrait.Format.EPOCH_SECONDS
                ? "decode_timestamp_epoch_seconds"
                : "decode_timestamp_date_time";
    }

    @SafeVarargs
    private static <T> List<T> concat(List<T>... lists) {
        List<T> out = new ArrayList<>();
        for (List<T> l : lists) {
            out.addAll(l);
        }
        return out;
    }

    private static String buildPathExpression(
            String uriTemplate,
            List<HttpBinding> labels,
            SymbolProvider sp,
            Model model) {
        if (labels.isEmpty()) {
            return "<<\"" + uriTemplate + "\">>";
        }
        StringBuilder sb = new StringBuilder("<<");
        int pos = 0;
        while (pos < uriTemplate.length()) {
            int start = uriTemplate.indexOf('{', pos);
            if (start < 0) {
                sb.append("\"").append(uriTemplate.substring(pos)).append("\"");
                break;
            }
            if (start > pos) {
                sb.append("\"").append(uriTemplate, pos, start).append("\", ");
            }
            int end = uriTemplate.indexOf('}', start);
            String labelName = uriTemplate.substring(start + 1, end);
            String fieldName = BeamNameUtils.toSnakeCase(labelName);
            sb.append("(uri_encode(to_binary(").append(toBindingVar(fieldName)).append(")))/binary");
            pos = end + 1;
            if (pos < uriTemplate.length()) {
                sb.append(", ");
            }
        }
        sb.append(">>");
        return sb.toString();
    }

    private static String resolvedRequestContentType(Model model, OperationShape op) {
        return BeamHttpBindings.from(model)
                .requestContentType(op, "application/json")
                .orElse("application/json");
    }

    private static String resolvedResponseContentType(Model model, OperationShape op) {
        return BeamHttpBindings.from(model)
                .responseContentType(op, "application/json")
                .orElse("application/json");
    }

    private static boolean responsePayloadRequiresContentTypeCheck(
            Model model, List<HttpBinding> respPayload) {
        if (respPayload.isEmpty()) {
            return false;
        }
        Shape target = model.expectShape(respPayload.get(0).getMember().getTarget());
        return target.hasTrait(MediaTypeTrait.class);
    }
